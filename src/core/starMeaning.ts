/// 获取星曜组合释义
export function getComboMeaning(starName: string, allStarNames: string[]): string {
    // 查找包含当前星曜的所有组合
    const combos: string[] = [];
    for (const [key, value] of Object.entries(STAR_COMBO_MEANING)) {
        const stars = key.split("+");
        if (stars.includes(starName)) {
            // 检查组合中的其他星曜是否也在同一宫位
            const otherStars = stars.filter((s) => s !== starName);
            if (otherStars.every((s) => allStarNames.includes(s))) {
                combos.push(value);
            }
        }
    }
    return combos.length > 0 ? combos.join("\n\n") : "";
}
